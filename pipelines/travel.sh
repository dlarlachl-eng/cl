#!/usr/bin/env bash
# 여행계획: Gemini 현지 정보 → Claude 일정표 → GPT 현실성 점검 → Claude 최종본
source "$(dirname "$0")/../lib/common.sh"
usage() { echo '사용법: ./ai.sh travel "도쿄 3박4일, 11월, 2인, 예산 150만원, 맛집 위주" [-f 항공숙소.txt]'; }
parse_args travel "$@"
P="$(profile)"

info=$(step 1 gemini 현지정보 "${P}여행 조건: $TOPIC
다음 현지 정보를 정리해줘 (최신 정보 기준, 확인이 필요한 건 표시).
1. 해당 시기 날씨, 축제·행사, 휴무 주의사항
2. 지역별 추천 명소·맛집 (위치, 대략적 가격, 예약 필요 여부)
3. 교통 (공항 이동, 교통패스, 이동 시간)
4. 예상 경비 항목$REF")

plan=$(step 2 claude 일정표 "${P}여행 조건: $TOPIC
아래 정보를 바탕으로 일자별 일정표를 만들어줘.
형식: 시간 | 장소 | 할 일 | 이동 방법·소요시간 | 예상 비용
동선이 겹치지 않게 지역별로 묶고, 비 오는 날 대안과 예산 합계표도 넣어줘.
[현지 정보]
$info$REF")

check=$(step 3 gpt 점검 "너는 꼼꼼한 여행 플래너야. 아래 일정을 점검해줘.
무리한 동선, 영업시간 충돌 가능성, 예산 초과, 빠진 예약, 체력 배분 문제를 찾아 수정안을 줘.
[일정표]
$plan")

step 4 claude 최종본 "${P}점검 의견을 반영해 최종 일정표를 만들어줘.
마지막에 '출발 전 체크리스트 (예약·준비물·앱)'와 '현지에서 꼭 다시 확인할 것 (영업시간, 가격 등)'을 추가해줘.
[일정표]
$plan
[점검 의견]
$check" >/dev/null

done_msg 4_최종본.md
