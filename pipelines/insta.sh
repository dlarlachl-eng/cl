#!/usr/bin/env bash
# 인스타 릴스: Claude 기획·대본 → GPT 트렌드·후킹 검토 → Claude 최종본
source "$(dirname "$0")/../lib/common.sh"
usage() { echo '사용법: ./ai.sh insta "릴스 주제" [-f 참고자료.txt]'; }
parse_args insta "$@"
P="$(profile)"

draft=$(step 1 claude 기획_대본 "${P}인스타그램 릴스 주제: $TOPIC
15~60초 세로 영상 기준으로 만들어줘.
1. 콘셉트 3안 (각각 한 줄 요약 + 왜 저장/공유될지)
2. 가장 좋은 안의 컷 구성표: 초 | 화면 | 화면 위 텍스트 | 나레이션/자막 | 전환
3. 첫 1.5초 훅 문구 5개
4. 촬영 체크리스트 (구도, 조명, 필요한 소품)$REF")

review=$(step 2 gpt 검토 "너는 인스타그램 릴스 전문가야. 아래 기획을 보고
스크롤이 멈추지 않을 지점, 너무 긴 컷, 약한 훅, 트렌드에 맞지 않는 부분을 지적하고 개선안을 줘.
[기획]
$draft")

step 3 claude 최종본 "${P}검토 의견을 반영해 최종 릴스 기획으로 정리해줘. 마지막에 다음도 추가해줘.
- 캡션 3안 (첫 줄 훅 + 본문 + 행동 유도)
- 해시태그 20개 (대형/중형/소형 섞어서)
- 커버 이미지 문구와 이미지 생성 프롬프트
[기획]
$draft
[검토 의견]
$review" >/dev/null

done_msg 3_최종본.md
