#!/usr/bin/env bash
# 유튜브 영상: Gemini 조사 → Claude 대본·편집계획 → GPT 시청자 관점 검토 → Claude 최종본
source "$(dirname "$0")/../lib/common.sh"
usage() { echo '사용법: ./ai.sh youtube "영상 주제" [-f 촬영본_자막.txt]'; }
parse_args youtube "$@"
P="$(profile)"

research=$(step 1 gemini 조사 "${P}유튜브 영상 주제: $TOPIC
이 주제로 영상을 만들려고 해. 다음을 정리해줘.
1. 핵심 사실과 최신 정보 (출처 포함)
2. 이 주제로 잘 된 영상들의 공통점과 시청자가 궁금해하는 질문
3. 차별화할 수 있는 관점 3가지$REF")

draft=$(step 2 claude 대본_편집계획 "${P}유튜브 영상 주제: $TOPIC
아래 조사 내용을 바탕으로 만들어줘.
1. 첫 15초 훅 3안
2. 전체 대본 (구간별 타임코드 포함)
3. 편집 계획표: 구간 | 화면(A롤/B롤/자료화면) | 자막 강조 문구 | 효과음·BGM 분위기 | 컷 전환
4. 촬영본 자막/대본이 참고자료로 있다면: 잘라낼 부분, 순서 변경, 줄일 부분을 타임코드로 지적
[조사 내용]
$research$REF")

review=$(step 3 gpt 검토 "너는 깐깐한 유튜브 시청자이자 채널 컨설턴트야.
아래 대본과 편집 계획을 보고 이탈이 생길 지점, 지루한 구간, 사실 오류, 더 나은 훅을 구체적으로 지적해줘.
[대본·편집계획]
$draft")

step 4 claude 최종본 "${P}아래 초안을 검토 의견을 반영해 최종본으로 다듬어줘. 마지막에 다음도 추가해줘.
- 제목 후보 5개 (클릭을 부르되 낚시는 아니게)
- 썸네일 문구 3개와 썸네일 이미지 생성 프롬프트 (ChatGPT/Gemini 이미지 생성에 붙여넣을 수 있게)
- 영상 설명란 텍스트와 태그 15개
[초안]
$draft
[검토 의견]
$review" >/dev/null

done_msg 4_최종본.md
